% TRAJECTORYPARAMS Parameters for Trajectory Generation
% This class provides a static configuration for reference trajectory generation.
%
% All spatial coordinates are defined in the North-West-Up (NWU) inertial frame.
% Time durations must be non-negative.
classdef TrajectoryParams
    
    properties (Constant)

        % Hover: Defines a stationary setpoint for steady flight.
        % pos in R^3 (m), psi in [-pi, pi] (rad).
        Hover = struct( ...
            'pos', [0.0; 0.0; 1.0], ...   
            'psi', 0.0 ...                
        );

        % Circle: Defines parameters for a circular path in the XY plane.
        % R > 0 (m), omega (rad/s), z_height (m), yaw_mode in {'tangent', 'fixed'}.
        Circle = struct( ...
            'R', 1.0, ...                 
            'omega', 1.0, ...             
            'z_height', 1.0, ...          
            'center', [0.0; 0.0], ...     
            'yaw_mode', 'tangent' ...     
        );

        % Lemniscate: Defines parameters for a figure-8 path in the XY plane.
        % R > 0 (m), omega (rad/s), z_height (m).
        Lemniscate = struct( ...
            'R', 1.0, ...                 
            'omega', 0.7, ...             
            'z_height', 1.0, ...          
            'center', [0.0; 0.0] ...        
        );

        % Spiral: Defines a 3D helical trajectory with climb and orientation logic.
        % R (m), omega (rad/s), vz (m/s), z_start (m).
        % yaw_mode in {'tangent', 'fixed'}:
        % 'tangent': Nose points toward the velocity vector (Coordinated Turn).
        % 'fixed':   Nose follows the independent Omega_yaw rate (Pirouette).
        Spiral = struct( ...
            'R', 1.0, ...                 
            'omega', 1.0, ...             
            'vz', 0.2, ...                
            'z_start', 0.5, ...           
            'Omega_yaw', 1.5, ...         
            'yaw_mode', 'tangent' ...     
        );

        % Ellipse: Defines parameters for an elliptical helical path.
        % Rx, Ry > 0 (m), omega (rad/s), vz (m/s), z_start (m).
        % yaw_mode in {'tangent', 'fixed'}:
        % 'tangent': Nose points toward velocity (varying yaw rate).
        % 'fixed':   Nose follows independent rate (Pirouette).
        Ellipse = struct( ...
            'Rx', 3.0, ...
            'Ry', 2.0, ...
            'omega', 0.7, ...
            'vz', 0.2, ...
            'z_start', 0.5, ...
            'Omega_yaw', 1.5, ...
            'yaw_mode', 'tangent' ...
        );

        % T_duration >= 0 (s).
        % T_duration_hover is 5 seconds.
        % T_duration_circle is calculated for exactly 1 lap around the circle (1*pi/omega).
        % T_duration_spiral is calculated for exactly 3 full revolutions (6*pi/omega).
        T_duration_hover  = 5.0; 
        T_duration_circle = (2 * pi) / 1.0;  
        T_duration_lemniscate = (2 * pi) / 0.7;
        T_duration_spiral = (6 * pi) / 1.0;  
        T_duration_ellipse = (4 * pi) / 0.7;
    end
end